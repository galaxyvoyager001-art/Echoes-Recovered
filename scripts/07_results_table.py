#!/usr/bin/env python3
"""Summarise the actual results into docs/RESULTS.md (every number comes from the
analysis/params files written by step 2 and the rights records from step 1)."""
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from restoration.text import name_case  # noqa: E402


def main():
    summ = json.loads((ROOT / "data" / "rights_verification_summary.json").read_text())
    rows, agg = [], {"nb": [], "na": [], "ib": [], "ia": [], "rep": [], "mid": []}
    for mp in sorted((ROOT / "data" / "metadata").glob("*.json")):
        m = json.loads(mp.read_text())
        if not m["rights"]["cleared_for_reuse"]:
            continue
        d = ROOT / "data" / "restored" / m["slug"]
        a = json.loads((d / "analysis.json").read_text())
        p = json.loads((d / "params.json").read_text())
        b, af, rc = a["before"], a["after"], a["removed_component"]
        rep = p["stage_log"][2]["percent_samples_replaced"] + p["stage_log"][3]["percent_samples_replaced"]
        w = b.get("wow") or {}
        rows.append((m["recording_date"], m["title"], name_case(m["primary_performer"]), m["recording_city"],
                     b["surface_noise_rms_dbfs"], af["surface_noise_rms_dbfs"], b["noise_floor_in_music_p5_dbfs"],
                     af["noise_floor_in_music_p5_dbfs"], b["impulses_per_min"], af["impulses_per_min"], rep,
                     rc["removed_vs_original_energy_300_3000hz_db"], f"{b['usable_band_hz'][0]}-{b['usable_band_hz'][1]}",
                     b.get("tuning_offset_cents_vs_A440"), w.get("peak_over_neighbourhood_db", 0.0), bool(b["hum"]),
                     f"[log](../data/restored/{m['slug']}/restoration_log.md)"))
        agg["nb"].append(b["surface_noise_rms_dbfs"]); agg["na"].append(af["surface_noise_rms_dbfs"])
        agg["ib"].append(b["impulses_per_min"]); agg["ia"].append(af["impulses_per_min"])
        agg["rep"].append(rep); agg["mid"].append(rc["removed_vs_original_energy_300_3000hz_db"])
    rows.sort()
    rej = [s for s in summ if not s["cleared"]]
    md = [f"# Results (generated by scripts/07_results_table.py)\n",
          f"* Candidates checked against LoC Rights & Access: **{len(summ)}**; cleared and restored: **{len(rows)}**; rejected: **{len(rej)}**.",
          f"* Median surface-noise level: **{st.median(agg['nb']):.1f} dBFS -> {st.median(agg['na']):.1f} dBFS** (median change {st.median([a - b for a, b in zip(agg['na'], agg['nb'])]):.1f} dB).",
          f"* Median impulses/min (AR detector, k=8): **{st.median(agg['ib']):.0f} -> {st.median(agg['ia']):.0f}**.",
          f"* Samples interpolated across clicks: median **{st.median(agg['rep']):.2f}%**, max {max(agg['rep']):.2f}% per track.",
          f"* Energy removed in 300-3000 Hz relative to the original: median **{st.median(agg['mid']):.1f} dB** (range {min(agg['mid']):.1f} to {max(agg['mid']):.1f} dB).",
          f"* Tracks with a 50/60 Hz peak flagged and notched: {sum(r[15] for r in rows)}. Speed/pitch corrections applied: 0. Generative/AI processing: none.\n",
          "Surface noise is measured in the lead-in groove where one exists, otherwise in the quietest frames. The impulse metric also counts strong musical attacks, so on loud dance-band records it overstates the remaining clicks.\n",
          "| Recorded | Title | Performer | City | Noise before | after (dBFS) | Floor in music before | after | Impulses/min before | after | Interpolated % | Removed 300-3k (dB) | Band (Hz) | Tuning (cents) | Wow peak (dB) | Hum | Log |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append("| " + " | ".join(f"{v:.2f}" if isinstance(v, float) and i == 10 else str(v) for i, v in enumerate(r)) + " |")
    md.append("\n## Rejected candidates\n")
    for s in rej:
        md.append(f"* `{s['id']}`: " + " ".join(x for x in s.get("reasons", [s.get("error", "")]) if x.startswith("FAIL")))
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(md) + "\n")
    # mirror the headline numbers into README.md between the RESULTS markers
    readme = ROOT / "README.md"
    if readme.exists():
        t = readme.read_text()
        a, b = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
        if a in t and b in t:
            cities = sorted({r[3] for r in rows})
            block = "\n".join([a, f"* 共核查 **{len(summ)}** 个 LoC 候选，**{len(rows)}** 首通过版权核查并完成修复，**{len(rej)}** 首被排除（理由见 [docs/RESULTS.md](docs/RESULTS.md)）。",
                               f"* 录制年份 {rows[0][0][:4]}–{rows[-1][0][:4]}；录制城市（按 LoC 记录）：{', '.join(cities)}。",
                               *md[2:7], "", "逐首数据见 [docs/RESULTS.md](docs/RESULTS.md)。", b])
            readme.write_text(t[: t.index(a)] + block + t[t.index(b) + len(b):])
    print("\n".join(md[:8]))


if __name__ == "__main__":
    main()
